(* Generated dispatch from registry.json. Actual calculations remain in the
   mathematical source modules. Result shape checks are not proof assumptions. *)
let pentagon_check_pair label (n,ok) =
  Printf.printf "RESULT %s: count=%d; returned=%b\n%!" label n ok;
  if n <= 0 || not ok then failwith ("Unsuccessful calculation: " ^ label);;
let pentagon_check_pairs label expected values =
  if List.length values <> expected then failwith ("Unexpected result count: " ^ label);
  List.iteri (fun i v -> pentagon_check_pair (Printf.sprintf "%s/%d" label i) v) values;;
